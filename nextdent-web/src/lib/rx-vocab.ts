/**
 * The vocabulary a field offers, widened by terms the clinic has already written.
 * Medical history is the case that needs this: its real-world list was mined from the
 * records and is ranked by use, so "NAD" and "HTN" must stay at the top while the
 * curated list fills in everything nobody has typed yet.
 */
export function mergeVocab(
  used: readonly string[],
  curated: readonly RxVocabOption[] = []
): RxVocabOption[] {
  const seen = new Set(used.map((t) => t.toLowerCase()));
  return [...used, ...curated.filter((o) => !seen.has(vocabValue(o).toLowerCase()))];
}
